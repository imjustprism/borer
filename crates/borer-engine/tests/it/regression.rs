/// A scalar single whose kept upper bits nothing reads is the single, not
/// a merge of its bits into the register.
#[test]
fn a_single_nothing_reads_above_is_no_merge() {
    let mut p = crate::raw::image(Arch::X86_64, DIST2_O0, &[]);
    p.format = BinaryFormat::Elf;
    let entry = p.entry.expect("entry");
    let text =
        decompile(&p, &Analysis::compute(&p), &Overlay::default(), entry).expect("decompile");
    assert!(!text.contains("0xffffffff"), "{text}");
    assert!(text.contains("(a3 - a1) * (a3 - a1)"), "{text}");
}
