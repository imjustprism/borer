/// Returns the name of a status code.
///
/// # Arguments
///
/// * `v` - An immediate as the decoder yields it: the 32-bit code, or the
///   code sign-extended to 64 bits, the way `cmp rax, imm32` carries it.
///
/// # Returns
///
/// The name, or `None` when the value is no code in the table.
pub fn name(v: u64) -> Option<&'static str> {
    let code = if v >> 32 == 0 || v >> 32 == 0xffff_ffff {
        u32::try_from(v & 0xffff_ffff).ok()?
    } else {
        return None;
    };
    let i = CODES.binary_search_by_key(&code, |&(c, _)| c).ok()?;
    CODES.get(i).map(|&(_, n)| n)
}

/// Returns the code a name stands for: the inverse of [`name`].
///
/// # Arguments
///
/// * `name` - A name as [`name`] gives it, `HRESULT_FROM_WIN32(...)` ones
///   included.
///
/// # Returns
///
/// The 32-bit code, or `None` for a name the table does not hold.
pub fn value(name: &str) -> Option<u32> {
    CODES.iter().find(|&&(_, n)| n == name).map(|&(c, _)| c)
}

#[cfg(test)]
mod tests {
    #![expect(
        clippy::missing_panics_doc,
        reason = "assertions are the point of a test"
    )]

    use super::{CODES, name, value};

    /// The table is sorted and free of duplicates, as the search needs.
    #[test]
    fn table_is_sorted_by_code() {
        assert!(
            CODES
                .windows(2)
                .all(|w| w.first().zip(w.get(1)).is_some_and(|(a, b)| a.0 < b.0))
        );
    }

    /// A code names itself whether it comes as 32 bits or sign-extended,
    /// and an unrelated value names nothing.
    #[test]
    fn codes_are_named_in_both_widths() {
        assert_eq!(name(0x800b_0100), Some("TRUST_E_NOSIGNATURE"));
        assert_eq!(name(0xffff_ffff_800b_0100), Some("TRUST_E_NOSIGNATURE"));
        assert_eq!(name(0xc000_0005), Some("STATUS_ACCESS_VIOLATION"));
        assert_eq!(name(0x1234), None);
        assert_eq!(name(0x1_800b_0100), None);
    }

    /// A name reads back as its code, and a name the table lacks as none.
    #[test]
    fn names_read_back_as_their_codes() {
        assert_eq!(value("TRUST_E_NOSIGNATURE"), Some(0x800b_0100));
        assert_eq!(
            value("HRESULT_FROM_WIN32(ERROR_FILE_NOT_FOUND)"),
            Some(0x8007_0002)
        );
        assert_eq!(value("NOT_A_CODE"), None);
    }
}
