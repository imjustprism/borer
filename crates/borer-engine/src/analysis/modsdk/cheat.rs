//! The mod SDK's globals as a Cheat Engine table (`.CT`), the XML Cheat
//! Engine 7 loads (`OpenSave.pas`, `MemoryRecordUnit.pas` at
//! cheat-engine/cheat-engine `ec45d5f4`).
//!
//! Each global is a record at `"module"+rva`. A pointer to a class the SDK
//! lays out is a group header with one zero offset, so CE follows the
//! pointer, and the class's fields are its children at `+offset` from the
//! object; a struct stored in place is a group header without the offset.
//! Numbers are hex without a prefix, as CE writes them; each description
//! says how sure the field is.

use std::fmt::Write as _;

use super::{Class, Evidence, Part, Sdk, Ty, parts, xml};

/// The table version Cheat Engine 7.6 writes (`_CurrentTableVersion`).
const TABLE_VERSION: u32 = 45;

/// Returns the globals of the SDK as a Cheat Engine table.
///
/// # Arguments
///
/// * `sdk` - What [`super::build`] gathered.
///
/// # Returns
///
/// The table's XML, starting `<?xml` as CE requires of a plain table.
#[must_use]
pub fn cheat_table(sdk: &Sdk) -> String {
    let mut out = format!(
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<CheatTable CheatEngineTableVersion=\"{TABLE_VERSION}\">\n  <CheatEntries>\n"
    );
    let mut id = 0u64;
    let module = xml(&sdk.module);
    for g in &sdk.globals {
        let address = format!("\"{module}\"+{:X}", sdk.rva(g.va));
        let (class, through) = match &g.ty {
            Ty::Ptr(Some(n)) => (sdk.class(n), true),
            Ty::Bytes(_, n) => (sdk.class(n), false),
            _ => (None, false),
        };
        let desc = describe(&g.name, &g.ty, &g.evidence);
        match class.filter(|c| !c.fields.is_empty()) {
            Some(c) => group(&mut out, &mut id, &desc, &address, through, c, sdk),
            None => entry(&mut out, &mut id, &desc, &address, &g.ty, sdk.word, "    "),
        }
    }
    out.push_str("  </CheatEntries>\n  <Comments>");
    let _ = write!(
        out,
        "Generated by borer from {module}. A field marked unsure is a guess at its type or extent; a recovered class may be bigger than its last field."
    );
    for (off, class) in &sdk.tls {
        let _ = write!(
            out,
            " Thread-local singleton {}: offset {off:#x} into the module's TLS block, which a CE address cannot name.",
            xml(class)
        );
    }
    out.push_str("</Comments>\n</CheatTable>\n");
    out
}

/// Writes a group header for an object, with a child per field.
///
/// # Arguments
///
/// * `out` - The table being written.
/// * `id` - The next record id, advanced past the records written.
/// * `desc` - The header's description.
/// * `address` - The global's address.
/// * `through` - The global points at the object, rather than holding it.
/// * `class` - The object's class.
/// * `sdk` - For the pointer width.
fn group(
    out: &mut String,
    id: &mut u64,
    desc: &str,
    address: &str,
    through: bool,
    class: &Class,
    sdk: &Sdk,
) {
    let offsets = if through {
        "\n      <Offsets>\n        <Offset>0</Offset>\n      </Offsets>"
    } else {
        ""
    };
    let _ = write!(
        out,
        "    <CheatEntry>\n      <ID>{id}</ID>\n      <Description>\"{}\"</Description>\n      <Options moHideChildren=\"1\"/>\n      <GroupHeader>1</GroupHeader>\n      <Address>{address}</Address>{offsets}\n      <CheatEntries>\n",
        xml(desc)
    );
    *id = id.saturating_add(1);
    for part in parts(class, sdk.word) {
        if let Part::Field(f) = part {
            let desc = describe(&f.name, &f.ty, &f.evidence);
            let at = format!("+{:X}", f.off);
            entry(out, id, &desc, &at, &f.ty, sdk.word, "        ");
        }
    }
    out.push_str("      </CheatEntries>\n    </CheatEntry>\n");
}

/// Writes one value's record.
///
/// # Arguments
///
/// * `out` - The table being written.
/// * `id` - The record's id, advanced past it.
/// * `desc` - Its description.
/// * `address` - Its address: `"module"+rva`, or `+offset` from its group.
/// * `ty` - Its type, which picks CE's variable type.
/// * `word` - The pointer width in bytes.
/// * `indent` - The record's indentation.
fn entry(
    out: &mut String,
    id: &mut u64,
    desc: &str,
    address: &str,
    ty: &Ty,
    word: u64,
    indent: &str,
) {
    let (kind, extra) = match ty {
        Ty::Int { bytes: 1, signed } => ("Byte", signed_flag(*signed)),
        Ty::Int { bytes: 2, signed } => ("2 Bytes", signed_flag(*signed)),
        Ty::Int { bytes: 8, signed } => ("8 Bytes", signed_flag(*signed)),
        Ty::Int { signed, .. } => ("4 Bytes", signed_flag(*signed)),
        Ty::Float => ("Float", String::new()),
        Ty::Double => ("Double", String::new()),
        Ty::Ptr(_) | Ty::VTable => (
            if word == 8 { "8 Bytes" } else { "4 Bytes" },
            "<ShowAsHex>1</ShowAsHex>".to_owned(),
        ),
        Ty::Bytes(n, _) => ("Array of byte", format!("<ByteLength>{n}</ByteLength>")),
    };
    let _ = writeln!(
        out,
        "{indent}<CheatEntry>\n{indent}  <ID>{id}</ID>\n{indent}  <Description>\"{}\"</Description>\n{indent}  <VariableType>{kind}</VariableType>{}\n{indent}  <Address>{address}</Address>\n{indent}</CheatEntry>",
        xml(desc),
        if extra.is_empty() {
            String::new()
        } else {
            format!("\n{indent}  {extra}")
        }
    );
    *id = id.saturating_add(1);
}

/// Returns the `ShowAsSigned` element of a signed integer, empty for an
/// unsigned one.
///
/// # Arguments
///
/// * `signed` - The integer is signed.
fn signed_flag(signed: bool) -> String {
    if signed {
        "<ShowAsSigned>1</ShowAsSigned>".to_owned()
    } else {
        String::new()
    }
}

/// Returns a record's description: its name, what it points at, and how
/// sure it is.
///
/// # Arguments
///
/// * `name` - The field's or global's name.
/// * `ty` - Its type.
/// * `evidence` - How it came to be known.
fn describe(name: &str, ty: &Ty, evidence: &Evidence) -> String {
    let what = match ty {
        Ty::Ptr(Some(n)) => format!(" -> {n}"),
        Ty::Bytes(_, n) => format!(" ({n})"),
        _ => String::new(),
    };
    match evidence {
        Evidence::Unsure(why) => format!("{name}{what} [unsure: {why}]"),
        Evidence::Stated | Evidence::Seen { .. } => format!("{name}{what}"),
    }
}
