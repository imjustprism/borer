//! The mod SDK as one C++ header.
//!
//! It holds a packed struct per class with padding between the fields
//! borer knows, `static_assert`s on their offsets and sizes, a struct of
//! the virtual slots per vtable, and the addresses of the vtables,
//! functions, globals and thread-local singletons relative to the image
//! base. Every struct is plain data (no virtual, no base), so `offsetof` holds
//! on it and the layout is exactly the one written: a derived class's
//! fields are flattened into its own, as its methods' accesses show them.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use super::{Class, Evidence, Part, Sdk, Size, Ty, ident, parts, unique};

/// The C++ names one header gives a program's classes.
struct Names {
    /// Class name to its struct's identifier.
    structs: BTreeMap<String, String>,
    /// Class name to its vtable struct's identifier.
    vtables: BTreeMap<String, String>,
}

/// Returns the mod SDK as a C++17 header.
///
/// # Arguments
///
/// * `sdk` - What [`super::build`] gathered.
///
/// # Returns
///
/// The header's text, the same bytes for the same SDK.
#[must_use]
pub fn header(sdk: &Sdk) -> String {
    let names = names(sdk);
    let mut out = prelude(sdk);
    for c in &sdk.classes {
        let _ = writeln!(out, "struct {};", names.structs[&c.name]);
        if c.vtable.is_some() {
            let _ = writeln!(out, "struct {};", names.vtables[&c.name]);
        }
    }
    out.push_str("\n#pragma pack(push, 1)\n");
    for c in &sdk.classes {
        out.push('\n');
        out.push_str(&vtable_struct(sdk, c, &names));
        out.push_str(&class_struct(sdk, c, &names));
    }
    out.push_str("\n#pragma pack(pop)\n");
    out.push_str(&addresses(sdk, &names));
    out.push_str("\n} // namespace sdk\n");
    out
}

/// Gives each class and vtable struct an identifier no other takes.
///
/// # Arguments
///
/// * `sdk` - The classes.
fn names(sdk: &Sdk) -> Names {
    let mut taken: BTreeSet<String> = ["rva", "global", "tls"]
        .into_iter()
        .map(str::to_owned)
        .collect();
    let structs: BTreeMap<String, String> = sdk
        .classes
        .iter()
        .map(|c| (c.name.clone(), unique(&mut taken, &ident(&c.name))))
        .collect();
    let vtables = sdk
        .classes
        .iter()
        .filter(|c| c.vtable.is_some())
        .map(|c| {
            let want = format!("{}_vftable", structs[&c.name]);
            (c.name.clone(), unique(&mut taken, &want))
        })
        .collect();
    Names { structs, vtables }
}

/// Returns the header's opening: what it is, how sure it is, the includes
/// and the pointer-width check.
///
/// # Arguments
///
/// * `sdk` - The program's facts.
fn prelude(sdk: &Sdk) -> String {
    let bits = sdk.word.saturating_mul(8);
    format!(
        "/*\n * Mod SDK for {module} ({bits}-bit), generated by borer.\n *\n * Preferred image base {base:#x}: every address below is relative to it;\n * add the module's load address. A field is \"stated\" when the overlay\n * states it, \"recovered\" when the class's methods access it at one width,\n * and \"unsure\" with the reason when the evidence is weaker. A recovered\n * class's size is only the end of its last field seen: the class may be\n * bigger. A derived class's fields are flattened into it. Check the\n * offsets against the running program before writing through them.\n */\n#pragma once\n#include <cstddef>\n#include <cstdint>\n\nnamespace sdk {{\n\nstatic_assert(sizeof(void*) == {word}, \"the module is a {bits}-bit image\");\n\n",
        module = comment(&sdk.module),
        base = sdk.image_base,
        word = sdk.word,
    )
}

/// Returns a class's vtable as a struct of its slots, empty when it has
/// no vtable.
///
/// # Arguments
///
/// * `sdk` - For the addresses.
/// * `class` - The class.
/// * `names` - The identifiers.
fn vtable_struct(sdk: &Sdk, class: &Class, names: &Names) -> String {
    let (Some(va), false) = (class.vtable, class.slots.is_empty()) else {
        return String::new();
    };
    let mut out = format!(
        "/* {}'s virtual table at rva {:#x}, {} slots */\nstruct {} {{\n",
        comment(&class.name),
        sdk.rva(va),
        class.slots.len(),
        names.vtables[&class.name]
    );
    let mut taken: BTreeSet<String> = [names.vtables[&class.name].clone()].into();
    for (i, (entry, name)) in class.slots.iter().enumerate() {
        let last = name.rsplit("::").next().unwrap_or(name);
        let last = last.rsplit('!').next().unwrap_or(last);
        let member = unique(&mut taken, &ident(last));
        let what = if *entry == 0 {
            "a data word, not a function".to_owned()
        } else {
            format!("rva {:#x} {}", sdk.rva(*entry), comment(name))
        };
        let _ = writeln!(out, "    void* {member}; /* [{i}] {what} */");
    }
    out.push_str("};\n");
    out
}

/// Returns a class as a packed struct with its `static_assert`s, or a
/// comment when it has no bytes to lay out.
///
/// # Arguments
///
/// * `sdk` - For the addresses and the pointer width.
/// * `class` - The class.
/// * `names` - The identifiers.
fn class_struct(sdk: &Sdk, class: &Class, names: &Names) -> String {
    let id = &names.structs[&class.name];
    let mut out = format!("/* {}", comment(&class.name));
    if let Some(p) = &class.parent {
        let _ = write!(out, "; parent {}", comment(p));
    }
    if let Some(v) = class.vtable {
        let _ = write!(out, "; vtable rva {:#x}", sdk.rva(v));
    }
    let _ = match class.size {
        Size::Stated(n) => write!(out, "; size {n:#x} (stated)"),
        Size::AtLeast(n) => write!(
            out,
            "; size at least {n:#x} (the end of the last field seen)"
        ),
    };
    for note in &class.notes {
        let _ = write!(out, "\n   note: {}", comment(note));
    }
    out.push_str(" */\n");
    if class.size.bytes() == 0 {
        let _ = writeln!(
            out,
            "/* {id}: no field is known, so it stays declared only */"
        );
        return out;
    }
    let mut taken: BTreeSet<String> = [id.clone()].into();
    let mut asserts = String::new();
    let _ = writeln!(out, "struct {id} {{");
    for part in parts(class, sdk.word) {
        match part {
            Part::Pad(off, len) => {
                let pad = unique(&mut taken, &format!("pad_{off:x}"));
                let _ = writeln!(out, "    std::uint8_t {pad}[{len:#x}];");
            }
            Part::Skipped(f) => {
                let _ = writeln!(
                    out,
                    "    /* +{:#x} {}: no room or no width; {} */",
                    f.off,
                    comment(&f.name),
                    comment(&f.evidence.to_string())
                );
            }
            Part::Field(f) => {
                let member = unique(&mut taken, &ident(&f.name));
                let (decl, what) = match &f.ty {
                    Ty::Bytes(n, what) => (
                        format!("std::uint8_t {member}[{n:#x}];"),
                        format!(" {}", comment(what)),
                    ),
                    ty => (
                        format!("{} {member};", c_type(ty, class, names)),
                        String::new(),
                    ),
                };
                let _ = writeln!(
                    out,
                    "    {decl} /* +{:#x}{what}{} */",
                    f.off,
                    comment(&evidence(&f.evidence))
                );
                let _ = writeln!(
                    asserts,
                    "static_assert(offsetof({id}, {member}) == {:#x}, \"{id}::{member}\");",
                    f.off
                );
            }
        }
    }
    out.push_str("};\n");
    out.push_str(&asserts);
    let _ = writeln!(
        out,
        "static_assert(sizeof({id}) == {:#x}, \"{id} size\");",
        class.size.bytes()
    );
    out
}

/// Returns the C++ type of a scalar or pointer field.
///
/// # Arguments
///
/// * `ty` - The field's type, not [`Ty::Bytes`].
/// * `class` - The class the field is in, whose vtable struct a
///   [`Ty::VTable`] points at.
/// * `names` - The identifiers, which say whether a pointee is defined.
///
/// # Returns
///
/// The type; a struct is named from `::sdk`, so a member spelled like it
/// cannot hide it.
fn c_type(ty: &Ty, class: &Class, names: &Names) -> String {
    match ty {
        Ty::Int { bytes, signed } => format!(
            "std::{}int{}_t",
            if *signed { "" } else { "u" },
            u32::from(*bytes).saturating_mul(8)
        ),
        Ty::Float => "float".to_owned(),
        Ty::Double => "double".to_owned(),
        Ty::Ptr(to) => to
            .as_ref()
            .and_then(|n| names.structs.get(n))
            .map_or_else(|| "void*".to_owned(), |id| format!("::sdk::{id}*")),
        Ty::VTable => names
            .vtables
            .get(&class.name)
            .map_or_else(|| "void*".to_owned(), |id| format!("::sdk::{id}*")),
        Ty::Bytes(..) => "std::uint8_t".to_owned(),
    }
}

/// Returns the evidence as the header's field comment says it after the
/// offset: nothing for a stated field.
///
/// # Arguments
///
/// * `e` - The evidence.
fn evidence(e: &Evidence) -> String {
    match e {
        Evidence::Stated => String::new(),
        e => format!(" {e}"),
    }
}

/// Returns the address tables: vtables and functions, globals, and the
/// thread-local singletons' offsets.
///
/// # Arguments
///
/// * `sdk` - The addresses.
/// * `names` - The vtable structs' identifiers, which name their tables.
fn addresses(sdk: &Sdk, names: &Names) -> String {
    let mut out = String::from("\n/* Addresses relative to the image base. */\nnamespace rva {\n");
    let mut taken = BTreeSet::new();
    for c in &sdk.classes {
        if let Some(v) = c.vtable {
            let id = unique(&mut taken, &names.vtables[&c.name]);
            let _ = writeln!(out, "constexpr std::uintptr_t {id} = {:#x};", sdk.rva(v));
        }
    }
    for (entry, name) in &sdk.functions {
        let id = unique(&mut taken, &ident(name));
        let _ = writeln!(
            out,
            "constexpr std::uintptr_t {id} = {:#x}; /* {} */",
            sdk.rva(*entry),
            comment(name)
        );
    }
    out.push_str("} // namespace rva\n\nnamespace global {\n");
    let mut taken = BTreeSet::new();
    for g in &sdk.globals {
        let id = unique(&mut taken, &ident(&g.name));
        let ty = match &g.ty {
            Ty::Ptr(Some(n)) => format!("{n} *"),
            Ty::Bytes(_, what) => what.clone(),
            Ty::Int { bytes, .. } => format!("{bytes} bytes"),
            Ty::Float => "float".to_owned(),
            Ty::Double => "double".to_owned(),
            Ty::Ptr(None) | Ty::VTable => "pointer".to_owned(),
        };
        let _ = writeln!(
            out,
            "constexpr std::uintptr_t {id} = {:#x}; /* {}: {} */",
            sdk.rva(g.va),
            comment(&ty),
            comment(&g.evidence.to_string())
        );
    }
    out.push_str(
        "} // namespace global\n\n/* Offsets into the module's TLS block. */\nnamespace tls {\n",
    );
    let mut taken = BTreeSet::new();
    for (off, class) in &sdk.tls {
        let id = unique(&mut taken, &ident(class));
        let _ = writeln!(
            out,
            "constexpr std::uintptr_t {id} = {off:#x}; /* {} *, unsure: a constructor stores its object here */",
            comment(class)
        );
    }
    out.push_str("} // namespace tls\n");
    out
}

/// Returns text safe inside a `/* */` comment.
///
/// # Arguments
///
/// * `text` - Any text; `*/`, `/*` and line breaks cannot end or nest the
///   comment.
fn comment(text: &str) -> String {
    text.replace("*/", "* /")
        .replace("/*", "/ *")
        .replace(['\n', '\r'], " ")
}
