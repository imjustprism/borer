//! The typed API library: what the functions an agent reads most return,
//! the names and C types of their parameters, and the constants those
//! parameters take.
//!
//! [`prototypes`](super::prototypes) knows the arity of eight thousand SDK
//! functions and nothing of their types. This is the typed layer over the
//! ones that matter most to a reader (files, memory, processes, the
//! registry, sockets, the C library, POSIX): a call to `CreateFileW` passes
//! `GENERIC_READ`, not `0x80000000`, a `void` API leaves no result for the
//! caller to bind, and `mmap(.., 3, ..)` protects `PROT_READ | PROT_WRITE`.
//!
//! The three tables beside this file are generated by
//! `scripts/check/typelib.py`, which states where every row comes from (the
//! public API documentation, restated as names and numbers) and
//! regenerates them byte for byte: `typelib.tsv` (the declarations),
//! `constants.tsv` (the constant groups) and `ctypes.tsv` (what the machine
//! passes each C type word as). A row names an API; nothing here invokes
//! one.

use std::collections::BTreeMap;
use std::sync::LazyLock;

use crate::num::sext32;
use crate::program::BinaryFormat;

/// The platform whose rows a declaration belongs to.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Os {
    /// The C standard library, which every platform has.
    C,
    /// POSIX and Linux: what an ELF or a Mach-O calls.
    Posix,
    /// The Windows API: what a PE calls.
    Win,
}

impl Os {
    /// Reads the table's word for a platform.
    ///
    /// # Arguments
    ///
    /// * `word` - `c`, `posix` or `win`.
    fn of(word: &str) -> Option<Self> {
        match word {
            "c" => Some(Self::C),
            "posix" => Some(Self::Posix),
            "win" => Some(Self::Win),
            _ => None,
        }
    }

    /// Tells whether a binary of `format` calls the functions of these rows.
    ///
    /// # Arguments
    ///
    /// * `format` - The binary's container format.
    #[must_use]
    pub fn serves(self, format: BinaryFormat) -> bool {
        match self {
            Self::C => matches!(
                format,
                BinaryFormat::Pe | BinaryFormat::Elf | BinaryFormat::MachO
            ),
            Self::Posix => matches!(format, BinaryFormat::Elf | BinaryFormat::MachO),
            Self::Win => format == BinaryFormat::Pe,
        }
    }
}

/// How a constant group names a value.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Kind {
    /// Bits: a value is the members it holds, widest first, and any bits no
    /// member covers in hex.
    Flags,
    /// Values: a value is the one member that states it exactly.
    Enum,
}

/// A named set of constants one parameter or result takes.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Group {
    /// Whether values are decomposed into bits or named whole.
    pub kind: Kind,
    /// `(value, name)` by ascending value; at most one member per value.
    pub members: Vec<(u64, &'static str)>,
}

/// Who pops a call's stack arguments on a 32-bit target, and where the
/// first ones go.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Conv {
    /// The caller pops them (`__cdecl`), as every variadic function does.
    Cdecl,
    /// The callee pops them (`__stdcall`, `WINAPI`).
    Stdcall,
    /// The callee pops them, the first two in `ecx` and `edx`
    /// (`__fastcall`).
    Fastcall,
}

/// One declared parameter.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Param {
    /// Its C type as the documentation spells it (`DWORD`, `const char *`).
    pub ty: &'static str,
    /// Its name (`dwDesiredAccess`).
    pub name: &'static str,
    /// The constant group its values are named from, if any.
    pub group: Option<&'static str>,
}

/// One function's declaration.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Decl {
    /// The function's name, as an import names it.
    pub name: &'static str,
    /// The platform it belongs to.
    pub os: Os,
    /// Its return type as spelled, `void` when it returns nothing.
    pub ret: &'static str,
    /// The constant group a caller compares the result with, if any.
    pub ret_group: Option<&'static str>,
    /// The fixed parameters, in order.
    pub params: Vec<Param>,
    /// A variable argument list follows the fixed parameters.
    pub variadic: bool,
    /// The calling convention on a 32-bit target.
    pub conv: Conv,
}

/// What the machine passes a C type as.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Pass {
    /// Nothing: `void`.
    Void,
    /// An integer of this many bits, signed or not, in a general register.
    Int {
        /// Width in bits: 8, 16, 32 or 64.
        bits: u8,
        /// Whether it is read as signed.
        signed: bool,
    },
    /// A float of this many bits (32 or 64), in a vector register.
    Float(u8),
    /// A pointer: the machine word, in a general register.
    Pointer,
}

impl Pass {
    /// The width in bits the value takes in its register.
    ///
    /// # Arguments
    ///
    /// * `word` - The machine word in bits (32 or 64).
    ///
    /// # Returns
    ///
    /// The width, 0 for `void`.
    #[must_use]
    pub fn bits(self, word: u8) -> u8 {
        match self {
            Self::Void => 0,
            Self::Int { bits, .. } | Self::Float(bits) => bits,
            Self::Pointer => word,
        }
    }
}

/// Counts the stack words a value takes on a 32-bit target: two for a
/// 64-bit integer or a `double`, one for anything else.
///
/// # Arguments
///
/// * `pass` - What the machine passes the value as, if known.
#[must_use]
pub fn words32(pass: Option<Pass>) -> usize {
    if matches!(pass, Some(Pass::Int { bits: 64, .. } | Pass::Float(64))) {
        2
    } else {
        1
    }
}

/// Splits a C type into its base words and the pointers over them.
///
/// Qualifiers and tags (`const`, `volatile`, `restrict`, `__unaligned`,
/// `struct`, `union`, `enum`) say nothing of how the value passes and are dropped; a `*` anywhere
/// counts one pointer, and a function type (`(`) counts as a pointer to
/// one.
///
/// # Arguments
///
/// * `spelled` - The type as written (`const char *`, `unsigned int`).
///
/// # Returns
///
/// The base words joined by single spaces (`char`, `unsigned int`) and the
/// pointer count.
#[must_use]
pub fn base_of(spelled: &str) -> (String, usize) {
    let stars = spelled.matches('*').count() + usize::from(spelled.contains('('));
    let base: Vec<&str> = spelled
        .split(|c: char| c == '*' || c.is_whitespace())
        .filter(|w| {
            !w.is_empty()
                && !matches!(
                    *w,
                    "const"
                        | "volatile"
                        | "struct"
                        | "union"
                        | "enum"
                        | "restrict"
                        | "__restrict"
                        | "__unaligned"
                        | "__ptr32"
                        | "__ptr64"
                )
        })
        .collect();
    (base.join(" "), stars)
}

/// Reads what the machine passes a C type as.
///
/// # Arguments
///
/// * `spelled` - The type as written.
/// * `word` - The machine word in bits (32 or 64).
/// * `format` - The binary's format: `long` is 32 bits on Windows and the
///   word elsewhere.
///
/// # Returns
///
/// The pass, or `None` when the type is a word neither the library nor
/// the SDK's typedefs ([`super::sdk::typedef`]) know and no pointer: a
/// name only the program defines, or a structure passed by value.
#[must_use]
pub fn pass_of(spelled: &str, word: u8, format: BinaryFormat) -> Option<Pass> {
    let (base, stars) = base_of(spelled);
    if stars > 0 {
        return Some(Pass::Pointer);
    }
    let long = if format == BinaryFormat::Pe { 32 } else { word };
    let int = |bits, signed| Some(Pass::Int { bits, signed });
    let known = CTYPES
        .get(base.as_str())
        .copied()
        .or_else(|| super::sdk::typedef(&base)?.pass)?;
    match known {
        "void" => Some(Pass::Void),
        "char" | "i8" => int(8, true),
        "u8" => int(8, false),
        "i16" => int(16, true),
        "u16" => int(16, false),
        "i32" => int(32, true),
        "u32" => int(32, false),
        "i64" => int(64, true),
        "u64" => int(64, false),
        "long" => int(long, true),
        "ulong" => int(long, false),
        "word" => int(word, false),
        "sword" => int(word, true),
        "f32" => Some(Pass::Float(32)),
        "f64" => Some(Pass::Float(64)),
        "ptr" => Some(Pass::Pointer),
        _ => None,
    }
}

/// Returns the declaration the library holds for a function a binary of
/// `format` calls.
///
/// A curated row comes first; the SDK library ([`super::sdk`]) answers
/// for every other function its headers declare.
///
/// # Arguments
///
/// * `name` - The function's bare name, matched exactly.
/// * `format` - The calling binary's format, which picks the platform's
///   rows.
///
/// # Returns
///
/// The declaration, or `None` when the library has none for that
/// platform.
#[must_use]
pub fn declared(name: &str, format: BinaryFormat) -> Option<&'static Decl> {
    let first = DECLS.partition_point(|d| d.name < name);
    DECLS
        .get(first..)
        .into_iter()
        .flatten()
        .take_while(|d| d.name == name)
        .find(|d| d.os.serves(format))
        .or_else(|| super::sdk::declared(name, |os| os.serves(format)))
}

/// Tells whether the import a linkage stub reaches takes an argument.
///
/// An import the library does not declare is taken to take one.
///
/// # Arguments
///
/// * `program` - The image, for its symbols and its format.
/// * `f` - The function.
///
/// # Returns
///
/// `None` when the function is no stub ([`super::Function::thunk`]).
pub(crate) fn stub_takes_arguments(
    program: &crate::program::Program,
    f: &super::Function,
) -> Option<bool> {
    let slot = f.thunk?;
    let import = program
        .symbols
        .iter()
        .find(|s| s.kind == crate::program::SymbolKind::Import && s.addr == slot);
    Some(
        import
            .and_then(|s| {
                declared(
                    super::bare_name(&crate::search::demangled_name(&s.name)),
                    program.format,
                )
            })
            .is_none_or(|d| !d.params.is_empty() || d.variadic),
    )
}

/// Returns what each function of a 64-bit program is declared to hand
/// back in `xmm0`.
///
/// The signature string a function carries comes first, then the return
/// type its debug information records, then the library's row for its
/// name ([`declared`]: `ceil` returns a `double`, `ceilf` a `float`).
///
/// # Arguments
///
/// * `program` - The image, for its debug information and its format.
/// * `functions` - Its functions.
///
/// # Returns
///
/// Per function, in order: `Some(Some(bits))` for a declared `float` (32)
/// or `double` (64), `Some(None)` for any other declared result, and
/// `None` when nothing declares the function or its type does not read.
pub(crate) fn declared_floats(
    program: &crate::program::Program,
    functions: &[super::Function],
) -> Vec<Option<Option<u8>>> {
    let debug: BTreeMap<u64, &str> = program
        .debug_functions
        .iter()
        .filter_map(|d| Some((d.low_pc, d.return_type.as_deref()?)))
        .collect();
    functions
        .iter()
        .map(|f| {
            let ret = match (&f.signature, debug.get(&f.entry)) {
                (Some(s), _) => s.ret.as_str(),
                (None, Some(&ty)) => ty,
                (None, None) => declared(super::bare_name(f.name.as_deref()?), program.format)?.ret,
            };
            Some(match pass_of(ret, 64, program.format)? {
                Pass::Float(bits) => Some(bits),
                Pass::Void | Pass::Int { .. } | Pass::Pointer => None,
            })
        })
        .collect()
}

